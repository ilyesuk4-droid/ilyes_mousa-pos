const dicts = { ar, fr };
export type TKey = keyof Dict;

interface I18n {
  lang: "ar" | "fr";
  t: (k: TKey) => string;
  money: (n: number) => string;
  fmtDate: (d: number) => string;
  setLang: (l: "ar" | "fr") => void;
  hideAmounts: boolean;
  toggleHideAmounts: () => void;
  darkMode: boolean;
  toggleDarkMode: () => void;
}
const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const settings = useData(() => settingsRepo.get(), []);
  const lang = settings?.language ?? "ar";
  const hideAmounts = !!settings?.hideAmounts;
  const darkMode = !!settings?.darkMode;

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  useEffect(() => {
    if (darkMode) {
      document.documentElement.classList.add("dark");
    } else {
      document.documentElement.classList.remove("dark");
    }
  }, [darkMode]);

  const value: I18n = {
    lang,
    t: (k) => dicts[lang][k] ?? k,
    money: (n) => `${new Intl.NumberFormat("fr-FR", { maximumFractionDigits: 2 }).format(n || 0)} ${lang === "ar" ? "دج" : "DA"}`,
    fmtDate: (d) => new Date(d).toLocaleString(lang === "ar" ? "ar-DZ" : "fr-FR", { dateStyle: "short", timeStyle: "short" }),
    setLang: (l) => void settingsRepo.save({ language: l }),
    hideAmounts,
    toggleHideAmounts: () => void settingsRepo.save({ hideAmounts: !hideAmounts }),
    darkMode,
    toggleDarkMode: () => void settingsRepo.save({ darkMode: !darkMode }),
  };
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}
export function useI18n() {
  const c = useContext(Ctx);
  if (!c) throw new Error("I18nProvider missing");
  return c;
}
